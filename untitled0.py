import json
import os
from datetime import datetime

ARCHIVO = "expedientes.json"

def cargar():
    if os.path.exists(ARCHIVO):
        with open(ARCHIVO, "r", encoding="utf-8") as f:
            return json.load(f)
    return []

def guardar(datos):
    with open(ARCHIVO, "w", encoding="utf-8") as f:
        json.dump(datos, f, ensure_ascii=False, indent=4)

def registrar(datos):
    nombre = input("Nombre completo: ").strip()
    dni = input("DNI (8 dígitos): ").strip()
    tipo = input("Tipo de trámite: ").strip()
    asunto = input("Asunto: ").strip()
    fecha = input("Fecha (AAAA-MM-DD): ").strip()
    area = input("Área de destino: ").strip()

    if not all([nombre, dni, tipo, asunto, fecha, area]):
        print("Error: completa todos los campos.")
        return
    if not dni.isdigit() or len(dni) != 8:
        print("Error: el DNI debe tener 8 dígitos.")
        return
    try:
        datetime.strptime(fecha, "%Y-%m-%d")
    except ValueError:
        print("Error: fecha inválida.")
        return

    numero = len(datos) + 1
    codigo = f"EXP-{numero:04d}"
    datos.append({
        "codigo": codigo, "nombre": nombre, "dni": dni,
        "tipo": tipo, "asunto": asunto, "fecha": fecha,
        "area": area, "estado": "Registrado"
    })
    guardar(datos)
    print("Expediente registrado:", codigo)

def buscar(datos):
    clave = input("Ingresa código o DNI: ").strip().lower()
    resultados = [e for e in datos if
                  e["codigo"].lower() == clave or e["dni"] == clave]
    if resultados:
        for e in resultados:
            print(e)
    else:
        print("Expediente no encontrado.")

def listar(datos):
    for e in sorted(datos, key=lambda x: (x["fecha"], x["codigo"])):
        print(e)

datos = cargar()

while True:
    print("\n--- MESA DE PARTES DIGITAL ---")
    print("1. Registrar expediente")
    print("2. Buscar expediente")
    print("3. Listar expedientes por fecha")
    print("4. Salir")
    opcion = input("Elige una opción: ")

    if opcion == "1":
        registrar(datos)
    elif opcion == "2":
        buscar(datos)
    elif opcion == "3":
        listar(datos)
    elif opcion == "4":
        print("Sistema finalizado.")
        break
    else:
        print("Opción inválida.")